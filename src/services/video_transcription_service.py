#!/usr/bin/env python3
"""
Video Transcription Service using Apify YouTube Scraper

Scrapes YouTube videos and extracts transcripts using Apify API.
Integrates with Airtable for storage and caching of transcriptions.
"""

import os
from typing import Optional, Dict, Any
from apify_client import ApifyClient
from dotenv import load_dotenv
from src.services.airtable_service import AirtableService

load_dotenv()

class VideoTranscriptionService:
    """Service for extracting YouTube transcripts using Apify"""

    def __init__(self, apify_api_token: Optional[str] = None):
        """
        Initialize the service

        Args:
            apify_api_token: Apify API token (defaults to APIFY_API_TOKEN env var)
        """
        self.apify_api_token = apify_api_token or os.getenv("APIFY_API_TOKEN")

        if not self.apify_api_token:
            raise ValueError("APIFY_API_TOKEN not found in environment variables")

        self.client = ApifyClient(self.apify_api_token)
        self.airtable = AirtableService()

        # Apify Actor ID for YouTube Scraper
        self.actor_id = "streamers/youtube-scraper"

    def extract_youtube_transcript(self, youtube_url: str) -> Optional[Dict[str, Any]]:
        """
        Extract transcript from YouTube video using Apify

        Args:
            youtube_url: YouTube video URL (e.g., https://youtu.be/VIDEO_ID)

        Returns:
            Dict with video metadata and transcript, or None if failed
            {
                "title": str,
                "transcript": str,
                "video_id": str,
                "url": str,
                "channel_name": str,
                "description": str,
                "view_count": int,
                "likes": int,
                "duration": str
            }
        """
        try:
            self.airtable.log_info("ApifyTranscription", f"Starting transcript extraction for: {youtube_url}")

            # Prepare Apify input
            run_input = {
                "startUrls": [{"url": youtube_url}],
                "maxResults": 1,
                "downloadSubtitles": True,
                "subtitlesLanguage": "en",
                "preferAutoGeneratedSubtitles": True,
                "subtitlesFormat": "plaintext",
                "maxResultsShorts": 0,
                "maxResultStreams": 0
            }

            # Run the Actor and wait for it to finish
            self.airtable.log_info("ApifyTranscription", "Calling Apify YouTube Scraper...")
            run = self.client.actor(self.actor_id).call(run_input=run_input)

            # Fetch results from the run's dataset
            items = list(self.client.dataset(run["defaultDatasetId"]).iterate_items())

            if not items:
                self.airtable.log_error("ApifyTranscription", "No results returned from Apify")
                return None

            # Get first (and only) video result
            video_data = items[0]

            # Extract transcript from subtitles
            transcript = None
            if "subtitles" in video_data and video_data["subtitles"]:
                for subtitle in video_data["subtitles"]:
                    if subtitle.get("type") == "auto_generated" and subtitle.get("language") == "en":
                        transcript = subtitle.get("plaintext")
                        break

            if not transcript:
                self.airtable.log_warning("ApifyTranscription", "No transcript found in Apify results")
                return None

            # Build structured response
            result = {
                "title": video_data.get("title", "Unknown"),
                "transcript": transcript,
                "video_id": video_data.get("id", ""),
                "url": video_data.get("url", youtube_url),
                "channel_name": video_data.get("channelName", ""),
                "description": video_data.get("text", ""),
                "view_count": video_data.get("viewCount", 0),
                "likes": video_data.get("likes", 0),
                "duration": video_data.get("duration", "")
            }

            self.airtable.log_info(
                "ApifyTranscription",
                f"Transcript extracted: {len(transcript)} characters from '{result['title']}'"
            )

            return result

        except Exception as e:
            error_msg = f"Failed to extract transcript from {youtube_url}: {str(e)}"
            self.airtable.log_error("ApifyTranscription", error_msg, stack_trace=str(e))
            return None

    def get_or_create_transcription(self, video_record_id: str, youtube_url: str) -> Optional[str]:
        """
        Get existing transcription from Airtable or create new one from YouTube URL

        Args:
            video_record_id: Airtable record ID for the video
            youtube_url: YouTube video URL to transcribe

        Returns:
            Transcript text or None if failed
        """
        try:
            # Check if transcription already exists
            uploads_table = self.airtable.api.table(self.airtable.base_id, self.airtable.media_uploads_table)
            record = uploads_table.get(video_record_id)

            existing_transcription = record["fields"].get("Transcription")
            transcription_status = record["fields"].get("Transcription Status", "")

            if existing_transcription and transcription_status == "Complete":
                self.airtable.log_info("ApifyTranscription", f"Using cached transcription for record: {video_record_id}")
                return existing_transcription

            # Update status to Processing
            uploads_table.update(video_record_id, {
                "Transcription Status": "Processing"
            })

            self.airtable.log_info("ApifyTranscription", f"Starting transcription for record: {video_record_id}")

            # Extract transcript using Apify
            result = self.extract_youtube_transcript(youtube_url)

            if result and result.get("transcript"):
                transcript = result["transcript"]

                # Store transcription and metadata in Airtable
                update_fields = {
                    "Transcription": transcript,
                    "Transcription Status": "Complete"
                }

                # Optionally store additional metadata
                if result.get("title"):
                    update_fields["Video Title"] = result["title"]

                uploads_table.update(video_record_id, update_fields)

                self.airtable.log_info(
                    "ApifyTranscription",
                    f"Transcription completed: {len(transcript)} characters"
                )

                return transcript
            else:
                uploads_table.update(video_record_id, {
                    "Transcription Status": "Failed"
                })
                self.airtable.log_error("ApifyTranscription", "Failed to extract transcript")
                return None

        except Exception as e:
            error_msg = f"Transcription process failed: {str(e)}"
            self.airtable.log_error("ApifyTranscription", error_msg, stack_trace=str(e))

            # Update status to Failed
            try:
                uploads_table = self.airtable.api.table(self.airtable.base_id, self.airtable.media_uploads_table)
                uploads_table.update(video_record_id, {
                    "Transcription Status": "Failed"
                })
            except:
                pass

            return None

    def check_dependencies(self) -> dict:
        """Check if all required dependencies are available"""
        status = {
            "apify_client": True,  # If we got here, it's installed
            "apify_api_token": bool(self.apify_api_token)
        }

        return status


def main():
    """Test the transcription service"""
    import sys

    try:
        service = VideoTranscriptionService()

        # Check dependencies
        deps = service.check_dependencies()
        print("Dependencies:")
        for dep, available in deps.items():
            status = "✅" if available else "❌"
            print(f"  {status} {dep}")

        if not all(deps.values()):
            print("\n❌ Missing dependencies:")
            if not deps.get("apify_api_token"):
                print("  # Set APIFY_API_TOKEN environment variable")
            return

        print("\n✅ Apify YouTube Transcription Service ready!")

        # Test with a YouTube URL if provided
        if len(sys.argv) > 1:
            youtube_url = sys.argv[1]
            print(f"\n🎬 Testing with: {youtube_url}")

            result = service.extract_youtube_transcript(youtube_url)

            if result:
                print(f"\n📊 Results:")
                print(f"  Title: {result['title']}")
                print(f"  Channel: {result['channel_name']}")
                print(f"  Views: {result['view_count']:,}")
                print(f"  Duration: {result['duration']}")
                print(f"  Transcript length: {len(result['transcript'])} characters")
                print(f"\n📝 First 200 characters of transcript:")
                print(f"  {result['transcript'][:200]}...")
            else:
                print("\n❌ Failed to extract transcript")
        else:
            print("\nUsage: python video_transcription_service.py <youtube_url>")
            print("Example: python video_transcription_service.py https://youtu.be/NhwKQ7GwGq8")

    except Exception as e:
        print(f"❌ Error: {e}")


if __name__ == "__main__":
    main()